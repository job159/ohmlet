/**
  ******************************************************************************
  * @file           : main.c
  * @brief          : lesson-i4-nomoe — lesson i4 (PWM), common mistake: TIM1
  *                   started without BDTR.MOE.
  ******************************************************************************
  * Identical to hal-tim-pwm except for the TIM1 start (USER CODE 2): TIM2 CH1
  * on PA0 (1 kHz, 25 %) and TIM3 CH1 on PA6 (20 kHz, 50 %) work, but TIM1 CH1
  * on PA8 stays silent because the Main Output Enable bit is never set. The
  * simulator logs a hint when TIM1 counts with CC1E = 1 and MOE = 0.
  *
  * Original description of hal-tim-pwm:
  * Blue Pill, 72 MHz (HSE 8 MHz × PLL9). APB1 = 36 MHz, so TIM2 and TIM3
  * count TIMXCLK = 2 × PCLK1 = 72 MHz; TIM1 sits on APB2 = 72 MHz (RM0008
  * §7.2, Figure 8). f_PWM = TIMXCLK / ((PSC + 1) · (ARR + 1)).
  *
  *   TIM2 CH1 → PA0: PSC 71 (1 MHz), ARR 999  → 1 kHz,  CCR1 250  → 25 %
  *   TIM3 CH1 → PA6: PSC 0 (72 MHz), ARR 3599 → 20 kHz, CCR1 1800 → 50 %
  *   TIM1 CH1 → PA8: PSC 71 (1 MHz), ARR 499  → 2 kHz,  CCR1 375  → 75 %
  *
  * PWM mode 1, active high: a channel is high while CNT < CCR1 and low
  * until the counter wraps (RM0008 §15.3.9), so every period starts with a
  * rising edge at the update event. TIM1 is an advanced-control timer: its
  * outputs stay disabled until BDTR.MOE is set (RM0008 §14.4.18) —
  * HAL_TIM_PWM_Start() does that for TIM1 (__HAL_TIM_MOE_ENABLE); a
  * register-level program has to set it itself.
  *
  * The CPU has nothing to do: after the timers are started it sleeps in
  * __WFI() (the SysTick interrupt wakes it once per millisecond).
  ******************************************************************************
  */
