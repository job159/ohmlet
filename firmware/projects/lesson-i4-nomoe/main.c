/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* Configure the system clock */
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  /* USER CODE BEGIN 2 */
  if (HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_1) != HAL_OK)
  {
    Error_Handler();
  }
  if (HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1) != HAL_OK)
  {
    Error_Handler();
  }
  /* MISTAKE (on purpose): TIM1 is started "by hand" the way a TIM2-4
     register-level program does it - CC1E and CEN only. TIM1 is an
     advanced-control timer: its outputs stay disabled until BDTR.MOE is set
     (RM0008 §14.4.18), so PA8 never shows the PWM although the counter runs
     and CCR1 matches. The fix: HAL_TIM_PWM_Start() (it calls
     __HAL_TIM_MOE_ENABLE) or TIM1->BDTR |= TIM_BDTR_MOE. */
  TIM1->CCER |= TIM_CCER_CC1E;
  TIM1->CR1 |= TIM_CR1_CEN;
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    __WFI();
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

