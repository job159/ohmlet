/**
  ******************************************************************************
  * @file           : main.c
  * @brief          : hal-adc-pot — ADC1 IN0 (PA0) single conversion every 100 ms.
  ******************************************************************************
  * Blue Pill, 72 MHz (HSE 8 MHz × PLL9), SysTick 1 kHz HAL time base.
  * ADCCLK = PCLK2 / 6 = 12 MHz (DS5319 Table 46: ≤ 14 MHz).
  * ADC1: independent mode, no scan, single conversion, software start,
  * right alignment, rank 1 = channel 0 (PA0, analog mode) with 55.5 cycles
  * of sampling: one conversion = (55.5 + 12.5) / 12 MHz = 5.67 µs.
  *
  * After HAL_ADCEx_Calibration_Start (RSTCAL, then CAL — RM0008 §11.4) the
  * main loop starts a conversion every SAMPLE_PERIOD_MS (deadline based,
  * no drift), polls EOC and prints on USART1 (PA9, 115200 8N1):
  *   "adc=<raw> mv=<mV>\r\n"   raw = 0..4095, mV = raw × 3300 / 4095 rounded
  * The first reading is printed right after initialisation.
  ******************************************************************************
  */
