/**
  ******************************************************************************
  * @file           : main.c
  * @brief          : hal-tim-encoder — quadrature encoder on TIM4 (PB6/PB7).
  ******************************************************************************
  * Blue Pill, 72 MHz. A quadrature (rotary) encoder: A → PB6 (TIM4_CH1),
  * B → PB7 (TIM4_CH2), common → GND; the inputs use the internal pull-ups.
  *
  * TIM4 in encoder mode 3 (TIM_ENCODERMODE_TI12, SMCR.SMS = 011, RM0008
  * §15.3.12): the counter counts EVERY edge of A and of B, up or down
  * depending on the level of the other signal (Table 87) — four counts per
  * quadrature cycle, and DIR shows the direction. With A leading B the
  * count goes up. Both inputs use the strongest digital filter (IC1F/IC2F
  * = 15), so contact bounce shorter than 3.6 µs is ignored.
  *
  * The main loop polls CNT (as a signed 16-bit position) and prints every
  * change on USART1 PA9 (115200 8N1):   enc=<position>\r\n
  * starting with "enc=0" at boot. It sleeps in __WFI() between SysTick
  * interrupts, so a change is reported within about 1 ms.
  ******************************************************************************
  */
