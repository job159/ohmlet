/**
  ******************************************************************************
  * @file           : main.c
  * @brief          : hal-i2c-scan — I2C1 bus scan with HAL_I2C_IsDeviceReady.
  ******************************************************************************
  * Blue Pill, 72 MHz (HSE 8 MHz x PLL9), SysTick 1 kHz HAL time base.
  * I2C1 on PB6 (SCL) / PB7 (SDA), alternate-function open drain, 100 kHz
  * standard mode: PCLK1 = 36 MHz, so HAL programs FREQ = 36, CCR = 180
  * (5 us high + 5 us low, RM0008 §26.6.8) and TRISE = 37. The bus needs
  * external pull-ups (e.g. 4.7 kOhm to 3.3 V on each line).
  * USART1 PA9 (TX) / PA10 (RX), 115200 8N1, for the report.
  *
  * Once after reset:
  *   "I2C1 scan 0x08-0x77\r\n"
  *   for every address 0x08 ... 0x77: HAL_I2C_IsDeviceReady(addr << 1,
  *   1 trial, 2 ms): START, address + W, ACK? -> "found 0xNN\r\n", STOP.
  *   A HAL_BUSY answer means the bus never became free (SDA or SCL held
  *   low, e.g. no pull-ups): "bus busy at 0xNN: SDA/SCL stuck low (pull-ups?)\r\n"
  *   and the scan stops; HAL_TIMEOUT (START never generated):
  *   "timeout at 0xNN\r\n" and the scan stops.
  *   "scan done N\r\n" (N = number of devices found).
  * Then the core sleeps (WFI between SysTick interrupts). Press reset to
  * scan again.
  ******************************************************************************
  */
/* USER CODE END Header */
/* Includes ------------------------------------------------------------------*/
#include "main.h"

