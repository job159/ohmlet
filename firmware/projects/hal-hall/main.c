/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* Configure the system clock */
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USART1_UART_Init();
  /* USER CODE BEGIN 2 */
  mini_printf("A3144 on PB12 (pull-up, EXTI12)\r\n");
  int shown = -1;
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    if (!changed)
    {
      __WFI();
      continue;
    }
    changed = 0;
    int magnet = HAL_GPIO_ReadPin(HALL_GPIO_Port, HALL_Pin) == GPIO_PIN_RESET;
    if (magnet == shown)
    {
      continue;
    }
    shown = magnet;
    HAL_GPIO_WritePin(LED_GPIO_Port, LED_Pin, magnet ? GPIO_PIN_RESET : GPIO_PIN_SET);
    mini_printf(magnet ? "magnet (OUT low)\r\n" : "no magnet (OUT high)\r\n");
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

