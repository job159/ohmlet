/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* Configure the system clock */
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_USART1_UART_Init();
  /* USER CODE BEGIN 2 */
  if (HAL_ADCEx_Calibration_Start(&hadc1) != HAL_OK)
  {
    Error_Handler();
  }
  mini_printf("ACS712-05B on PA0: %d mV = 0 A, %d mV/A\r\n", ZERO_MV, SENS_MV_PER_A);
  uint32_t next = HAL_GetTick();
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    if ((int32_t)(HAL_GetTick() - next) < 0)
    {
      __WFI();
      continue;
    }
    next += REPORT_PERIOD_MS;
    uint32_t sum = 0;
    for (uint32_t i = 0; i < SAMPLES; i++)
    {
      if (HAL_ADC_Start(&hadc1) != HAL_OK || HAL_ADC_PollForConversion(&hadc1, 10) != HAL_OK)
      {
        Error_Handler();
      }
      sum += HAL_ADC_GetValue(&hadc1);
    }
    /* mV = sum / 16 x 3300 / 4095, rounded */
    int32_t mv = (int32_t)((sum * VDDA_MV + (SAMPLES * 4095U) / 2U) / (SAMPLES * 4095U));
    int32_t diff = mv - ZERO_MV;
    /* mA = diff / 0.185 = diff x 1000 / 185, rounded half away from zero */
    int32_t ma = (diff * 1000 + (diff >= 0 ? SENS_MV_PER_A / 2 : -SENS_MV_PER_A / 2)) / SENS_MV_PER_A;
    mini_printf("I=%ld mA (out %ld mV)%s\r\n", (long)ma, (long)mv, sum >= SAMPLES * 4094U ? " (ADC full scale)" : "");
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

